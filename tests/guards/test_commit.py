def test_the_log_is_bounded_scrubbed_and_terminated(monkeypatch: pytest.MonkeyPatch) -> None:
    """The three properties of the one `git` this module runs, each asserted where it can fail.

    A bound, a scrubbed environment and a closed argument list are all invisible to a test that
    only checks the return value: deleting any of the three leaves every other test in this
    file green.
    """
    import subprocess as sp

    seen: dict[str, object] = {}
    argv_seen: list[str] = []

    def fake(argv: list[str], **kwargs: object) -> sp.CompletedProcess[bytes]:
        seen.update(kwargs)
        argv_seen.extend(argv)
        return sp.CompletedProcess(argv, 0, stdout=b"", stderr=b"")

    # A `GIT_DIR` the session happens to carry makes git answer for a different repository
    # than the one the range is about; `scrubbed_env` is what drops it. Outside a hook, where
    # `git_run` hands git this process's own `PATH`, so the expected environment is the plain
    # scrubbed one and no `git` on this machine is needed to reach `fake`.
    launched_by_the_hook_wrapper(monkeypatch, False)
    monkeypatch.setenv("GIT_DIR", "/elsewhere/.git")
    monkeypatch.setattr(sp, "run", fake)
    # The bound is read below `git_run`, where the suite's floor has already lifted it: at the
    # product's zero, or a dropped `timeout=` would reach `fake` as the floor and pass.
    monkeypatch.delenv(gitenv.FLOOR_VARIABLE)
    assert commits_in(Path("/nowhere"), "a..b") == []

    # `seen["timeout"] == LOG_TIMEOUT_SECONDS` alone is an expectation read from the subject
    # under test: both sides move together, so it survives every edit to the constant and
    # reddens only when `timeout=` is dropped entirely. The fixed literal is its pair.
    assert seen["timeout"] == LOG_TIMEOUT_SECONDS
    assert LOG_TIMEOUT_SECONDS == 60

    env = seen["env"]
    assert isinstance(env, dict)
    assert "GIT_DIR" not in env
    assert env == gitenv.scrubbed_env()

    # `--` last, and the range before it: without the terminator a range that names an
    # existing file is read as a pathspec and the log silently answers about something else.
    assert argv_seen[-2:] == ["a..b", "--"]
