@needs_git
def test_a_control_byte_in_a_body_does_not_split_the_commit_into_two_records(
    tmp_path: Path,
) -> None:
    """One `\\x01` in a body voided the gate for that commit. Measured, not foreseen.

    `%x01` was the record separator, chosen for "neither can occur in a commit message". NUL
    cannot; `\\x01` can, and git stores it. On the shipped module this fixture measured:

        commits_in returned 2 record(s) for one commit
          sha='5bf5be35eaab'  offences=[]
          sha=' in it.\\n\\nCo-'  offences=[]

    The record split, the remainder of the message landed in the field read as a `sha`, the
    count went 1 -> 2 and the trailer travelled in a record nothing judged. Both assertions are
    needed: a reader that returned one record holding only the text before the `\\x01` would
    satisfy the count and still miss the trailer.

    `--cleanup=verbatim` is what gets the byte past `git commit`'s own message cleanup; it is
    not exotic, it is the mode `-F` with a prepared file is routinely used in.
    """
    root = repo(tmp_path)
    message = (
        "fix: sneaky\n"
        "\n"
        "A body line carrying \x01 in it.\n"
        "\n"
        "Co-Authored-By: Claude <noreply@anthropic.com>\n"
    )
    path = tmp_path / "msg"
    path.write_text(message, encoding="utf-8")
    (root / "sneaky.txt").write_text("x\n", encoding="utf-8")
    git(root, "add", "-A")
    git(root, "commit", "-q", "--cleanup=verbatim", "-F", str(path))

    commits = commits_in(root, "base..HEAD")
    assert len(commits) == 1
    assert commits[0].sha == git(root, "rev-parse", "HEAD").strip()
    assert offending_lines(commits[0].message) == [
        Offence(5, "attribution trailer naming an AI tool")
    ]


