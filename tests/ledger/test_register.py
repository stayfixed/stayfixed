"""The ledger engine serves any register, and the bug ledger is one value of it, byte for byte.

The two literals below were captured from the engine before it took a register, and are not
derived from the code under test: every project's manifest records the empty index's digest, so
a change to those bytes is an upgrade every project sees, not a refactor.

stayfixed:ledger:fixtures — the identifiers below are sample data, not claims about a ledger.
"""

